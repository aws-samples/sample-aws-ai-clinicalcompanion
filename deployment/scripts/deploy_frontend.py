"""
Deploy frontend to S3 + CloudFront.

This script:
1. Reads CDK outputs (WebSocket URL, HTTP API, Cognito config, CloudFront)
2. Generates frontend/config.js with the correct values
3. Uploads all frontend files to S3
4. Invalidates CloudFront cache

Usage:
    python deployment/scripts/deploy_frontend.py
"""

import boto3
import json
import os
import sys
import mimetypes
import logging

# Add parent path for config import
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from config import AWS_PROFILE, AWS_REGION, AWS_ACCOUNT_ID

logging.basicConfig(level=logging.INFO, format='%(message)s')
logger = logging.getLogger(__name__)

FRONTEND_DIR = os.path.join(os.path.dirname(__file__), '..', '..', 'frontend')
STACK_NAME = 'ClinicalCompassStack'


def get_session():
    return boto3.Session(profile_name=AWS_PROFILE, region_name=AWS_REGION)


def get_stack_outputs(session):
    """Read CDK stack outputs."""
    cf = session.client('cloudformation')
    try:
        response = cf.describe_stacks(StackName=STACK_NAME)
        outputs = {}
        for output in response['Stacks'][0].get('Outputs', []):
            outputs[output['OutputKey']] = output['OutputValue']
        return outputs
    except Exception as e:
        logger.error(f"Failed to read stack outputs: {e}")
        sys.exit(1)


def generate_config_js(outputs):
    """Generate frontend/config.js from CDK outputs."""
    ws_url = outputs.get('WebSocketUrl', '')
    http_api_url = outputs.get('HttpApiEndpoint', '')
    cognito_pool_id = outputs.get('CognitoUserPoolId', '')
    cognito_client_id = outputs.get('CognitoClientId', '')

    config_content = f"""/**
 * ClinicalCompass Frontend Configuration
 * Auto-generated by deploy_frontend.py — DO NOT EDIT MANUALLY
 */

const config = {{
  // REST API endpoint for patient/guideline data
  apiBaseUrl: '{http_api_url}',

  // WebSocket API endpoint
  websocketUrl: '{ws_url}',

  // Cognito authentication
  cognitoUserPoolId: '{cognito_pool_id}',
  cognitoClientId: '{cognito_client_id}',
  cognitoRegion: '{AWS_REGION}',

  // Feature flags
  useWebSocket: true,

  // Connection settings
  maxReconnectAttempts: 5,
  reconnectDelay: 1000,
  pingIntervalMs: 30000,

  // UI settings
  autoScroll: true,
  showTimestamps: true,
  maxResponseLength: 50000
}};

// Export for use in modules
if (typeof module !== 'undefined' && module.exports) {{
  module.exports = config;
}}
"""
    config_path = os.path.join(FRONTEND_DIR, 'config.js')
    with open(config_path, 'w') as f:
        f.write(config_content)
    logger.info(f"✓ Generated config.js")
    logger.info(f"    websocketUrl = {ws_url}")
    logger.info(f"    apiBaseUrl = {http_api_url}")
    logger.info(f"    cognitoUserPoolId = {cognito_pool_id}")
    logger.info(f"    cognitoClientId = {cognito_client_id}")


def upload_frontend(session, bucket_name):
    """Upload all frontend files to S3."""
    s3 = session.client('s3')
    frontend_path = os.path.abspath(FRONTEND_DIR)
    uploaded = 0

    # Directories to skip (not part of the frontend app)
    skip_dirs = {'node_modules', '.git', '__pycache__', '.venv'}
    # Files to skip
    skip_files = {'package.json', 'package-lock.json', 'README.md', 'config.example.js'}

    for root, dirs, files in os.walk(frontend_path):
        # Skip excluded directories
        dirs[:] = [d for d in dirs if d not in skip_dirs and not d.startswith('.')]

        for filename in files:
            if filename.startswith('.') or filename in skip_files:
                continue

            filepath = os.path.join(root, filename)
            key = os.path.relpath(filepath, frontend_path)

            # Determine content type
            content_type, _ = mimetypes.guess_type(filepath)
            if content_type is None:
                content_type = 'application/octet-stream'

            # Upload
            extra_args = {'ContentType': content_type}

            # Set cache headers
            if filename == 'config.js' or filename == 'index.html':
                extra_args['CacheControl'] = 'no-cache, no-store, must-revalidate'
            elif filename.endswith('.js') and (key.startswith('js/') or key.startswith('lib/')):
                # Frontend application logic changes frequently; force revalidation
                # so browsers do not keep stale auth or WebSocket code after deploys.
                extra_args['CacheControl'] = 'no-cache, no-store, must-revalidate'
            elif filename.endswith(('.js', '.css')):
                extra_args['CacheControl'] = 'public, max-age=3600'
            else:
                extra_args['CacheControl'] = 'public, max-age=86400'

            s3.upload_file(filepath, bucket_name, key, ExtraArgs=extra_args)
            uploaded += 1

    logger.info(f"✓ Uploaded {uploaded} files to s3://{bucket_name}")


def invalidate_cloudfront(session, distribution_id):
    """Invalidate CloudFront cache."""
    cf = session.client('cloudfront')
    import time
    caller_ref = f"deploy-{int(time.time())}"

    cf.create_invalidation(
        DistributionId=distribution_id,
        InvalidationBatch={
            'Paths': {'Quantity': 1, 'Items': ['/*']},
            'CallerReference': caller_ref,
        }
    )
    logger.info(f"✓ CloudFront cache invalidation initiated")


def main():
    logger.info("═══ ClinicalCompass Frontend Deployment ═══\n")

    session = get_session()

    # 1. Read stack outputs
    logger.info("Reading CDK stack outputs...")
    outputs = get_stack_outputs(session)

    bucket_name = outputs.get('FrontendBucketName', '')
    distribution_id = outputs.get('CloudFrontDistributionId', '')
    cloudfront_url = outputs.get('CloudFrontUrl', '')

    if not bucket_name:
        logger.error("FrontendBucketName not found in stack outputs. Run 'cdk deploy' first.")
        sys.exit(1)

    # 2. Generate config.js with dynamic values
    logger.info("\nGenerating frontend config...")
    generate_config_js(outputs)

    # 3. Upload frontend files to S3
    logger.info(f"\nUploading frontend to S3...")
    upload_frontend(session, bucket_name)

    # 4. Invalidate CloudFront cache
    if distribution_id:
        logger.info(f"\nInvalidating CloudFront cache...")
        invalidate_cloudfront(session, distribution_id)

    # 5. Print access URL
    logger.info(f"\n{'═' * 50}")
    logger.info(f"✅ Frontend deployed successfully!")
    logger.info(f"{'═' * 50}")
    if cloudfront_url:
        logger.info(f"\n🌐 Access URL: {cloudfront_url}")
    logger.info("\n📋 Create a Cognito user before login (see README.md or infra/README.md).")


if __name__ == '__main__':
    main()
